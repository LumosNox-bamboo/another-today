export interface CareerDuty {
  id: string;
  title: string;
  process: string;
  success: string;
  setback: string;
  skill: number;
  hours?: [number, number];
}
export interface CareerTrack {
  id: string;
  name: string;
  job: Character['job'];
  scene: Scene;
  activity: Activity;
  hours: [number, number];
  daysOff: number[];
  skills: [string, string, string];
  stages: [string, string, string, string];
  directions: [string, string];
  duties: CareerDuty[];
}
function track(
  id: string,
  name: string,
  job: Character['job'],
  scene: Scene,
  activity: Activity,
  hours: [number, number],
  daysOff: number[],
  skills: CareerTrack['skills'],
  stages: CareerTrack['stages'],
  directions: CareerTrack['directions'],
  rows: string[],
): CareerTrack {
  return {
    id,
    name,
    job,
    scene,
    activity,
    hours,
    daysOff,
    skills,
    stages,
    directions,
    duties: rows.map((row, i) => {
      const [title, process, success, setback] = row.split('|');
      return { id: `${id}-${i}`, title, process, success, setback, skill: i % 3 };
    }),
  };
}
