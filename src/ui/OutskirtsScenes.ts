import type { Scene } from '../engine/model';
import type { PixelPainter } from './PixelWorld';

export function drawOutskirts(
  p: PixelPainter,
  scene: Scene,
  t: number,
  night: boolean,
  open: boolean,
) {
  const { r, line, ellipse, plant, window, table, shelf, tree, lamp } = p;
  if (scene === 'riverside') {
    r(0, 123, 480, 42, '#8faaa0');
    for (let x = 20; x < 480; x += 88) tree(x, 126, 0.55);
    r(0, 159, 480, 64, night ? '#63858f' : '#90bbbe');
    r(0, 162, 480, 5, '#b3cec5');
    for (let i = 0; i < 28; i++)
      line(((i * 67 + t * 7) % 500) - 20, 171 + (i % 5) * 9, 13 + (i % 4) * 6, '#c4d8ce');
    // Low bridge with three square arches on the far bank.
    r(40, 145, 203, 12, '#a3937d');
    r(38, 141, 207, 5, '#c1b69e');
    for (const x of [49, 110, 173, 230]) r(x, 152, 9, 44, '#a3937d');
    for (let x = 45; x < 243; x += 22) {
      r(x, 124, 3, 18, '#7f8c80');
    }
    r(42, 124, 200, 3, '#7f8c80');
    const boatX = 288 + Math.sin(t * 0.11) * 23;
    r(boatX, 186, 46, 8, '#9b795c');
    r(boatX + 5, 194, 35, 4, '#806a55');
    r(boatX + 13, 172, 20, 14, '#e4d5af');
    r(boatX + 16, 176, 5, 5, '#7a9e9f');
    r(boatX + 25, 176, 5, 5, '#7a9e9f');
    r(0, 224, 480, 86, '#c8c1a4');
    for (let y = 239; y < 310; y += 18) line(0, y, 480, '#b8b498');
    r(0, 223, 480, 6, '#8d927d');
    for (let x = 12; x < 480; x += 40) {
      r(x, 210, 4, 24, '#7e8879');
    }
    r(0, 208, 480, 4, '#a5ae98');
    for (let i = 0; i < 15; i++) {
      const x = 349 + ((i * 17) % 120),
        y = 205 + (i % 3) * 7;
      r(x, y - 24, 2, 32, '#7f9269');
      r(x - 2, y - 30, 5, 11, '#ad9770');
    }
    r(67, 246, 73, 6, '#b19067');
    r(70, 259, 67, 7, '#c4a578');
    r(74, 265, 4, 17, '#80785f');
    r(129, 265, 4, 17, '#80785f');
    lamp(27, 231, night);
  }
  if (scene === 'greenhouse') {
    r(39, 78, 402, 73, '#a0c4b4');
    for (let x = 45; x < 438; x += 49) {
      r(x, 84, 42, 57, night ? '#6e9692' : '#c2dfce');
      r(x + 3, 87, 6, 46, '#eff4d850');
      r(x + 43, 78, 4, 72, '#6c9b87');
    }
    r(37, 106, 405, 4, '#7fa591');
    r(39, 78, 402, 5, '#779d88');
    for (const [x, y] of [
      [59, 165],
      [276, 165],
      [60, 222],
      [277, 222],
    ]) {
      table(x, y, 132, 20);
      for (let i = 0; i < 5; i++) plant(x + 14 + i * 25, y + 4, 0.7 + (i % 2) * 0.16);
      r(x + 4, y + 22, 115, 13, '#a5ad88');
    }
    r(212, 133, 38, 22, '#8a9b75');
    r(216, 137, 30, 15, '#e5e4bd');
    for (let y = 140; y < 152; y += 4) line(220, y, 20, '#8fa184');
    r(404, 230, 24, 29, '#7da2a0');
    r(401, 228, 30, 4, '#9cbaba');
    r(216, 249, 17, 11, '#789e90');
    r(232, 245, 9, 4, '#789e90');
  }
  if (scene === 'workshop') {
    window(65, 88, 61, 46, night);
    r(161, 86, 133, 58, '#aa8565');
    for (let x = 167; x < 288; x += 10) for (let y = 93; y < 140; y += 10) r(x, y, 2, 2, '#795f4d');
    for (const x of [176, 206, 241, 269]) {
      r(x, 105, 4, 25, '#d1b28c');
      r(x - 5, 100, 15, 7, '#75817c');
    }
    shelf(354, 87, 63, 73);
    table(67, 190, 137, 32);
    table(265, 205, 142, 30);
    r(80, 195, 52, 17, '#e1c29a');
    line(84, 202, 42, '#b89770');
    r(142, 192, 31, 22, '#9cbbb0');
    r(149, 197, 16, 3, '#e4d5ac');
    r(156, 191, 3, 21, '#e4d5ac');
    for (let i = 0; i < 6; i++)
      r(276 + i * 17, 212, 13, 10, ['#b1b99a', '#bd8d7b', '#d3bc8b'][i % 3]);
    r(225, 220, 23, 29, '#b59770');
    r(223, 217, 27, 5, '#d1b289');
    for (let i = 0; i < 12; i++) r(90 + ((i * 29) % 280), 248 + (i % 3) * 4, 5, 2, '#d7b78a');
    lamp(328, 164, night);
  }
  if (scene === 'market') {
    r(0, 128, 480, 182, '#cec3a5');
    for (let y = 148; y < 310; y += 16) {
      line(0, y, 480, '#bbb398');
      for (let x = y % 32; x < 480; x += 40) r(x, y, 1, 15, '#bbb398');
    }
    for (const [x, color] of [
      [20, '#a3b596'],
      [180, '#d0aa76'],
      [340, '#b3938c'],
    ] as const) {
      r(x + 6, 136, 4, 87, '#937b60');
      r(x + 111, 136, 4, 87, '#937b60');
      r(x, 113, 122, 28, color);
      for (let a = 0; a < 6; a++) r(x + a * 20, 113, 10, 34, '#e8dac0');
      r(x, 147, 122, 4, '#8e7c65');
      table(x + 4, 190, 114, 23);
      r(x + 10, 213, 100, 18, color);
      for (let i = 0; i < 6; i++) {
        r(
          x + 12 + i * 16,
          179 + (i % 2) * 3,
          12,
          12,
          x < 100
            ? ['#bc8b61', '#8da270'][i % 2]
            : x < 300
              ? ['#c2a879', '#9bafa2'][i % 2]
              : ['#b395a5', '#d4c2a0'][i % 2],
        );
      }
      if (!open) {
        r(x + 8, 176, 106, 19, '#b4ad95');
        r(x, 112, 122, 40, '#a9a18a');
        for (let y = 117; y < 149; y += 7) line(x + 3, y, 116, '#c0b79e');
      }
      r(x + 85, 163, 22, 16, '#e9dfbd');
      line(x + 89, 170, 13, '#9b927b');
    }
    tree(20, 261, 0.8);
    tree(452, 269, 0.7);
    r(173, 278, 66, 6, '#b1a58d');
    r(179, 284, 4, 13, '#8c816d');
    r(228, 284, 4, 13, '#8c816d');
  }
  if (scene === 'theater') {
    r(39, 78, 402, 74, '#5f646c');
    r(84, 101, 312, 81, '#879891');
    r(96, 109, 286, 59, '#c9c4a4');
    r(79, 172, 320, 17, '#9b765d');
    r(86, 190, 306, 9, '#b49472');
    r(129, 143, 36, 29, '#afbc9e');
    r(136, 124, 22, 22, '#b7c5ab');
    r(288, 136, 42, 36, '#d6bea0');
    r(300, 148, 17, 24, '#a4aca0');
    for (const x of [44, 384])
      for (let i = 0; i < 5; i++)
        r(x + i * 9, 81, 9, 110 - (i % 2) * 13, i % 2 ? '#975f68' : '#ad767b');
    if (!open) for (let x = 83; x < 385; x += 12) r(x, 91, 12, 84, x % 24 ? '#ad767b' : '#975f68');
    r(40, 78, 400, 13, '#af797c');
    for (const x of [115, 231, 345]) {
      r(x, 86, 13, 10, '#575b5e');
      r(x + 2, 94, 9, 4, '#f4d6a0');
    }
    for (const y of [223, 251])
      for (let x = 65; x < 418; x += 58) {
        r(x, y - 13, 27, 16, '#9a777b');
        r(x - 1, y + 2, 29, 7, '#bb9291');
        r(x + 3, y + 9, 3, 8, '#7c6d66');
        r(x + 22, y + 9, 3, 8, '#7c6d66');
      }
  }
  if (scene === 'observatory') {
    r(0, 129, 480, 181, night ? '#707f87' : '#a1af9d');
    for (let i = 0; i < 8; i++) r(i * 64, 130 + (i % 3) * 7, 64, 26, night ? '#64767d' : '#91a48e');
    r(141, 222, 199, 88, '#b5b3a2');
    for (let y = 236; y < 310; y += 16) line(144, y, 193, '#9d9f93');
    r(75, 153, 105, 76, '#c1c4b7');
    r(85, 131, 85, 25, '#a3b8b4');
    r(98, 118, 59, 15, '#a3b8b4');
    r(114, 111, 27, 9, '#a3b8b4');
    r(127, 113, 6, 43, '#758e92');
    r(70, 152, 115, 6, '#899c98');
    window(94, 170, 25, 28, night);
    r(142, 183, 24, 46, '#7f9695');
    // Telescope on the observation deck; never aimed at the sun.
    r(285, 208, 5, 39, '#707c80');
    r(273, 245, 29, 4, '#707c80');
    for (let i = 0; i < 5; i++) r(267 + i * 8, 183 + i * 5, 14, 14, '#d5d4bf');
    r(262, 179, 12, 17, '#859caa');
    r(307, 207, 12, 8, '#718591');
    r(359, 183, 58, 39, '#8e998e');
    r(363, 187, 50, 30, '#d4d6bf');
    for (let i = 0; i < 8; i++)
      r(369 + (i % 4) * 11, 193 + Math.floor(i / 4) * 12, 3, 3, '#8898a1');
    r(364, 222, 4, 20, '#8d8e7b');
    r(408, 222, 4, 20, '#8d8e7b');
    lamp(197, 212, night);
    for (let i = 0; i < 12; i++) ellipse(28 + i * 39, 287 + (i % 2) * 12, 6, 3, '#8b968c');
  }
}
