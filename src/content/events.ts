import { outskirtsEvents } from './outskirtsEvents';
import type { Activity, Scene, World } from '../engine/model';
export type Gate =
  | 'any'
  | 'employed'
  | 'friend'
  | 'partner'
  | 'student'
  | 'night'
  | 'rain'
  | 'plant'
  | 'single'
  | 'weekend';
export interface EventDefinition {
  eventId: string;
  category: string;
  title: string;
  description: string;
  triggerConditions: { activities: Activity[]; gate: Gate };
  weight: number;
  cooldown: number;
  participants: 'self' | 'npc';
  playerChoiceRequired: boolean;
  choices: string[];
  effects: { mood: number; stress: number; money: number };
  followUpEvents: string[];
  requiresEvent?: { id: string; days: number };
  memoryTags: string[];
  rarity: 'common' | 'uncommon';
  scenes?: Scene[];
  requiredState?: 'gift' | 'habit' | 'npc-change' | 'news' | 'creation';
  season?: '春' | '夏' | '秋' | '冬';
  branch?: {
    trait: keyof World['character']['traits'];
    threshold: number;
    text: string;
    mood: number;
  };
  repeatPolicy: 'cooldown' | 'once';
}
export const events: EventDefinition[] = [];
function group(
  category: string,
  activities: Activity[],
  rows: string,
  gate: Gate = 'any',
  mood = 3,
  stress = -1,
  money = 0,
) {
  rows
    .trim()
    .split('\n')
    .forEach((line, i) => {
      const [title, description] = line.split('|');
      events.push({
        eventId: `event-${events.length + 1}`,
        category,
        title,
        description,
        triggerConditions: {
          activities,
          gate: ['雨滴敲着窗', '避开一场小雨'].includes(title) ? 'rain' : gate,
        },
        weight: 1,
        cooldown: (2 + (i % 5)) * 1440,
        participants: gate === 'friend' || gate === 'partner' ? 'npc' : 'self',
        playerChoiceRequired: false,
        choices: [],
        effects: { mood, stress, money },
        followUpEvents: [],
        memoryTags: [category, title],
        rarity: i % 4 === 0 ? 'uncommon' : 'common',
        repeatPolicy: 'cooldown',
      });
    });
}
