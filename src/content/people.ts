export function createWorld(
  character: Character = structuredClone(defaultCharacter),
  now = Date.now(),
  seed = 20261017,
): World {
  const d = new Date(now);
  const t = Date.UTC(d.getFullYear(), d.getMonth(), d.getDate(), 8, 0);
  const w: World = {
    version: 1,
    seed: seed >>> 0 || 1,
    sequence: 0,
    time: t,
    simulatedUntil: Math.floor(t / STEP) * STEP,
    lastReal: now,
    createdReal: now,
    character: structuredClone(character),
    needs: { energy: 85, hunger: 28, mood: 78, stress: 18, social: 25, fun: 70, health: 90 },
    money: character.housing === '合租小屋' ? 1800 : 3000,
    activity: { kind: 'wash', start: t, end: t + 15 * 60000, scene: 'apartment' },
    recentActivities: [],
    npcs: residents.map(([name, job, interest], i) => ({
      id: `npc-${i}`,
      name,
      job,
      interest,
      age: 21 + (i % 14),
      traits: Object.fromEntries(
        Object.entries(defaultTraits).map(([k], j) => [k, 20 + ((i * 17 + j * 23) % 75)]),
      ) as Traits,
      scene: i % 2 ? 'park' : 'cafe',
      plan: '开始新的一天',
      memories: [],
      relation: {
        familiarity: i === 0 ? 18 : 0,
        affection: 45 + (i % 15),
        trust: 15,
        intimacy: 0,
        conflict: 0,
        type: i === 0 ? '邻居' : '陌生人',
        dates: 0,
        willing: i % 3 !== 0,
      },
    })),
    events: [],
    memories: [],
    diaries: [],
    playerDiaries: [],
    cooldowns: {},
    flags: { lastShop: t, lastGarden: t },
    chains: [],
    decisions: [],
    items: [
      {
        id: 'plant',
        name: '窗边的绿萝',
        description: '搬进来时带来的小植物。它和你一起慢慢长大。',
        acquired: t,
        source: '入住',
        uses: 0,
        anchor: 'plant',
      },
      {
        id: 'shelf',
        name: '旧木书架',
        description: '从旧物市场带回来的书架，边角有一点磨损。',
        acquired: t,
        source: '入住',
        uses: 0,
        anchor: 'shelf',
      },
      {
        id: 'desk',
        name: '第一张书桌',
        description: '从这里开始画画、写作，也开始新的生活。',
        acquired: t,
        source: '入住',
        uses: 0,
        anchor: 'desk',
      },
    ],
    evolution: [],
    playerActivities: [],
    companion: { familiarity: 0, trust: 20, conversations: 0, sharedMinutes: 0 },
    settings: { speed: 4, offlineDays: 7, advice: 'important', sound: false, volume: 0.2 },
    ledger: [],
    lastSalaryDay: '',
    lastRentDay: '',
  };
  record(
    w,
    '搬进梧桐街',
    `${character.name}放下行李，在${character.housing}开始了新的生活。`,
    '人生',
    true,
    'arrival',
  );
  return w;
}
